<script>
jQuery(document).ready(function($){
    var $box = $('#hiv-calculator-52');
    var $form = $box.find('#health_form_52');
    $form.on('submit',function(event){
        event.preventDefault();
        var hasRisk = $box.find('input[value="yes"]:checked').length > 0;
        var $result = $box.find('.result-text');
        $result.empty();
        if(hasRisk){
            $result.text('Bạn có yếu tố cần lưu ý liên quan đến nguy cơ phơi nhiễm HIV. Bạn nên được tư vấn và xét nghiệm HIV để xác định tình trạng nhiễm HIV.');
        }else{
            $result.text('Dựa trên các thông tin bạn cung cấp, công cụ chưa ghi nhận yếu tố nguy cơ nào trong 9 câu hỏi. Tuy vậy, nếu có nghi ngờ về việc phơi nhiễm HIV, bạn nên được tư vấn và xét nghiệm.');
        }
        $box.find('.result-container').show();
    });
});
</script>